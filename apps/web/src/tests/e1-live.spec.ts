import { expect, test } from '@playwright/test';
declare const process: { env: Record<string, string | undefined> };

test('isolated HTTP: account lifecycle and enterprise ownership', async ({ page }) => {
  test.skip(process.env.HUICE_E1_LIVE !== '1', 'requires isolated E1 fixture server');
  const suffix = Date.now().toString(36);
  const first = `a.${suffix}`;
  const second = `b.${suffix}`;
  const password = 'synthetic-pass-12345';
  const register = async (name: string) => {
    await page.getByRole('button', { name: '注册账号' }).click();
    await page.getByLabel('用户名').fill(name);
    await page.getByLabel('密码', { exact: true }).fill(password);
    await page.getByLabel('企业名称').fill(`合成${name}`);
    await page.getByLabel('地区代码').fill('440300');
    await page.getByLabel('行业代码').fill('C39');
    await page.getByRole('button', { name: '注册', exact: true }).click();
    await expect(page.getByText('注册成功，请登录。')).toBeVisible();
  };
  const login = async (name: string) => {
    await page.getByLabel('用户名').fill(name);
    await page.getByLabel('密码', { exact: true }).fill(password);
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await expect(page.getByRole('button', { name: '账号与退出' })).toBeVisible();
  };
  await page.goto('/#enterprise');
  await register(first);
  await login(first);
  await expect(page.getByText(`已保存合成企业：合成${first}`)).toBeVisible();
  await page.getByRole('button', { name: '编辑行业' }).click();
  await page.getByLabel('值', { exact: true }).fill('F51');
  const patchResponse = page.waitForResponse(response => response.url().includes('/facts/industry') && response.request().method() === 'PATCH');
  await page.getByRole('button', { name: '保存该项' }).click();
  expect((await patchResponse).status()).toBe(200);
  await expect(page.getByRole('status')).toContainText('该项信息已保存');
  const me = await page.request.get('http://127.0.0.1:8000/api/v1/auth/me');
  expect(me.status()).toBe(200);
  const enterpriseId = (await me.json()).user.enterpriseId;
  await page.reload();
  await expect(page.getByText(`已保存合成企业：合成${first}`)).toBeVisible();
  await expect(page.getByText(/行业代码：F51/)).toBeVisible();
  await page.getByRole('button', { name: '账号与退出' }).click();
  await page.getByRole('button', { name: '退出并切换账号' }).click();
  await register(second);
  await login(second);
  await expect(page.getByText(`已保存合成企业：合成${second}`)).toBeVisible();
  expect((await page.request.get(`http://127.0.0.1:8000/api/v1/enterprises/${enterpriseId}`)).status()).toBe(404);
  await page.getByRole('button', { name: '账号与退出' }).click();
  await page.getByLabel('当前密码').fill(password);
  await page.getByLabel('新密码').fill('synthetic-new-pass-12345');
  await page.getByRole('button', { name: '修改密码' }).click();
  await expect(page.getByText('密码已更新，请重新登录。')).toBeVisible();
  expect((await page.request.get('http://127.0.0.1:8000/api/v1/auth/me')).status()).toBe(401);
});

test('isolated HTTP: reviewer session controls audit access', async ({ page, request }) => {
  test.skip(process.env.HUICE_E1_LIVE !== '1', 'requires isolated E1 fixture server');
  const username = `review.${Date.now().toString(36)}`;
  const otherName = `合成只读${Date.now()}`;
  const period = { startDate: '2026-01-01', endDate: '2026-12-31' };
  const registered = await request.post('http://127.0.0.1:8000/api/v1/auth/register', { headers: { Origin: 'http://127.0.0.1:5173' }, data: { username: `other.${Date.now().toString(36)}`, password: 'synthetic-pass-12345', enterprise: { nameSynthetic: otherName, period, facts: [{ key: 'region', value: '440300', unit: 'code', period, source: 'user_input' }, { key: 'industry', value: 'C39', unit: 'code', period, source: 'user_input' }] } } });
  expect(registered.status()).toBe(201);
  await page.goto('/#admin');
  await page.getByRole('button', { name: '注册账号' }).click();
  await page.getByLabel('用户名').fill(username);
  await page.getByLabel('密码', { exact: true }).fill('synthetic-pass-12345');
  await page.getByLabel('审核员注册密钥（仅审核员）').fill('synthetic-reviewer-key-12345');
  await page.getByRole('button', { name: '注册', exact: true }).click();
  await expect(page.getByText('注册成功，请登录。')).toBeVisible();
  await page.getByLabel('密码', { exact: true }).fill('synthetic-pass-12345');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('button', { name: '政策审核' })).toBeVisible();
  const me = await page.request.get('http://127.0.0.1:8000/api/v1/auth/me');
  expect((await me.json()).user.role).toBe('reviewer');
  const response = await page.request.get('http://127.0.0.1:8000/api/v1/admin/policies');
  expect(response.status()).toBe(200);
  await page.getByLabel('版本', { exact: true }).fill(`v${Date.now()}`);
  await page.getByLabel('标题', { exact: true }).fill('审核员合成测试');
  await page.getByLabel('发布机关').fill('合成机构');
  await page.getByLabel('地区', { exact: true }).fill('440300');
  await page.getByLabel('发布日期').fill('2026-01-01');
  await page.getByLabel('生效日期').fill('2026-01-01');
  await page.getByLabel('官方原文网址').fill('https://www.gov.cn/');
  await page.getByLabel('官方办理网址').fill('https://www.gov.cn/');
  await page.getByLabel('适用主体（每行一项）').fill('企业');
  await page.getByLabel('政策正文（PDF 或 UTF-8 文本）').setInputFiles('src/tests/fixtures/phase5-synthetic.txt');
  const imported = page.waitForResponse(result => result.url().endsWith('/admin/policies/import') && result.request().method() === 'POST');
  await page.getByRole('button', { name: '导入草稿' }).click();
  const importResponse = await imported;
  expect(importResponse.status()).toBe(201);
  expect(importResponse.request().headers()['x-csrf-token']).toBeTruthy();
  expect(importResponse.request().headers()['authorization']).toBeUndefined();
  const denied = await page.request.post('http://127.0.0.1:8000/api/v1/admin/policies/import', { headers: { Origin: 'http://127.0.0.1:5173' }, multipart: {} });
  expect(denied.status()).toBe(403);
  expect((await denied.json()).error.code).toBe('CSRF_REQUIRED');
  await expect(page.getByRole('button', { name: '处理轨迹' })).toHaveCount(0);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '企业与运行记录' }).click();
  await page.getByRole('button', { name: '读取企业列表' }).click();
  await page.getByRole('button', { name: otherName }).click();
  await expect(page.getByRole('heading', { name: otherName })).toBeVisible();
  await expect(page.getByRole('button', { name: /编辑行业|保存该项/ })).toHaveCount(0);
});

test('restricted HTTP: gate expiry does not discard the user session', async ({ page, context }) => {
  test.skip(process.env.HUICE_E1_RESTRICTED !== '1', 'requires isolated restricted fixture server');
  const cookie = process.env.HUICE_E1_COOKIE!;
  await page.goto('/#enterprise');
  await expect(page.getByRole('heading', { name: '演示入口已失效' })).toBeVisible();
  await context.addCookies([{ name: 'huice_demo_session', value: cookie, url: 'http://127.0.0.1:8000' }]);
  await page.getByRole('button', { name: '重新检查会话' }).click();
  await expect(page.getByRole('heading', { name: '登录', exact: true })).toBeVisible();
  const username = `gate.${Date.now().toString(36)}`;
  await page.getByRole('button', { name: '注册账号' }).click();
  await page.getByLabel('用户名').fill(username);
  await page.getByLabel('密码', { exact: true }).fill('synthetic-pass-12345');
  await page.getByLabel('企业名称').fill('门禁合成企业');
  await page.getByLabel('地区代码').fill('440300');
  await page.getByLabel('行业代码').fill('C39');
  await page.getByRole('button', { name: '注册', exact: true }).click();
  await expect(page.getByText('注册成功，请登录。')).toBeVisible();
  await page.getByLabel('密码', { exact: true }).fill('synthetic-pass-12345');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByText('已保存合成企业：门禁合成企业')).toBeVisible();
  await context.clearCookies({ name: 'huice_demo_session' });
  await page.getByRole('button', { name: '机会列表' }).click();
  await expect(page.getByRole('heading', { name: '演示入口已失效' })).toBeVisible();
  await context.addCookies([{ name: 'huice_demo_session', value: cookie, url: 'http://127.0.0.1:8000' }]);
  await page.getByRole('button', { name: '重新检查会话' }).click();
  await expect(page.getByText(username, { exact: true })).toBeVisible();
});
