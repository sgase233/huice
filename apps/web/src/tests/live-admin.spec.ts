import { expect, test } from '@playwright/test';
declare const process: { env: Record<string, string | undefined> };

test('隔离后端：导入、抽取、编辑和发布合成政策', async ({ page }) => {
  test.skip(process.env.HUICE_LIVE_ADMIN !== '1', '仅在确认专用隔离后端时运行');
  test.setTimeout(90_000);
  const title = `第五阶段合成审核 ${Date.now()}`;
  await page.route('**/api/v1/**', route => new URL(route.request().url()).origin === 'http://127.0.0.1:8000' ? route.continue() : route.abort());
  await page.goto('/#admin');
  await page.getByLabel('管理令牌').fill(process.env.HUICE_LIVE_ADMIN_TOKEN ?? '');
  await page.getByRole('button', { name: '使用令牌' }).click();
  await page.getByLabel('版本', { exact: true }).fill(`v${Date.now()}`);
  await page.getByLabel('标题', { exact: true }).fill(title);
  await page.getByLabel('发布机关').fill('合成测试机关');
  await page.getByLabel('地区', { exact: true }).fill('440300');
  await page.getByLabel('发布日期').fill('2026-01-01');
  await page.getByLabel('生效日期').fill('2026-01-01');
  await page.getByLabel('官方原文网址').fill('https://www.gov.cn/');
  await page.getByLabel('官方办理网址').fill('https://www.gov.cn/');
  await page.getByLabel('适用主体（每行一项）').fill('企业');
  await page.getByLabel('政策正文（PDF 或 UTF-8 文本）').setInputFiles('src/tests/fixtures/phase5-synthetic.txt');
  const imported = page.waitForResponse(response => response.url().endsWith('/admin/policies/import') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '导入草稿' }).click();
  const policyId = ((await (await imported).json()) as { id: string }).id;
  await expect(page.getByRole('button', { name: '抽取条款' })).toBeEnabled();
  await page.getByRole('button', { name: '抽取条款' }).click();
  await expect(page.getByText(/抽取模式：固定样例/)).toBeVisible();
  await page.getByLabel('标题', { exact: true }).last().fill('合成所得额条件');
  await page.getByRole('button', { name: '保存并校验' }).click();
  await expect(page.getByRole('status')).toHaveText('条件已保存，服务端校验结果已更新。');
  await page.getByLabel('我已人工核对条件及来源').check();
  await expect(page.getByRole('button', { name: '确认发布' })).toBeEnabled();
  await page.getByRole('button', { name: '确认发布' }).click();
  await expect(page.getByText(/发布请求已成功/)).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '企业画像' }).click();
  await page.getByRole('button', { name: '保存当前样本' }).click();
  await expect(page.getByText('已保存合成企业：合成企业 A')).toBeVisible();
  await page.getByRole('button', { name: '机会列表' }).click();
  const policy = page.locator('article').filter({ hasText: title });
  await policy.getByRole('checkbox').check();
  await page.getByRole('button', { name: '分析所选政策' }).click();
  await expect(policy.getByText(/还缺资料|满足条件|不满足条件/)).toBeVisible();
  await page.getByRole('button', { name: '处理轨迹' }).click();
  await page.getByRole('button', { name: '读取轨迹' }).click();
  await expect(page.getByText(/规则判断/).first()).toBeVisible();
  await page.getByRole('button', { name: '政策审核' }).click();
  await page.getByLabel('已有政策 ID（新政策留空）').fill(policyId);
  await page.getByLabel('版本', { exact: true }).fill(`v${Date.now()}-new`);
  await page.getByLabel('标题', { exact: true }).fill(title);
  await page.getByLabel('发布机关').fill('合成测试机关');
  await page.getByLabel('地区', { exact: true }).fill('440300');
  await page.getByLabel('发布日期').fill('2026-01-01');
  await page.getByLabel('生效日期').fill('2026-01-01');
  await page.getByLabel('官方原文网址').fill('https://www.gov.cn/');
  await page.getByLabel('官方办理网址').fill('https://www.gov.cn/');
  await page.getByLabel('适用主体（每行一项）').fill('企业');
  await page.getByLabel('政策正文（PDF 或 UTF-8 文本）').setInputFiles('src/tests/fixtures/phase5-synthetic.txt');
  await page.getByRole('button', { name: '导入草稿' }).click();
  await expect(page.getByRole('button', { name: '抽取条款' })).toBeEnabled();
  await page.getByRole('button', { name: '抽取条款' }).click();
  await expect(page.getByText(/抽取模式：固定样例/)).toBeVisible();
  await page.getByLabel('标题', { exact: true }).last().fill('更新的合成所得额条件');
  await page.getByRole('button', { name: '保存并校验' }).click();
  await expect(page.getByRole('status')).toHaveText('条件已保存，服务端校验结果已更新。');
  await page.getByLabel('我已人工核对条件及来源').check();
  await page.getByRole('button', { name: '确认发布' }).click();
  await expect(page.getByText(/发布请求已成功/)).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '机会列表' }).click();
  await expect(page.locator('article').filter({ hasText: title }).getByText('依据已失效，待复核')).toBeVisible();
});
