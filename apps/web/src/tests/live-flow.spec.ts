import { expect, test } from '@playwright/test';
declare const process: { env: Record<string, string | undefined> };

test('隔离后端真实 HTTP：行业排除与缺失事实', async ({ page }) => {
  test.skip(process.env.HUICE_LIVE !== '1', '仅在明确启动隔离联调服务时运行');
  await page.route('**/api/v1/**', route => {
    const url = new URL(route.request().url());
    return url.origin === 'http://127.0.0.1:8000' ? route.continue() : route.abort('blockedbyclient');
  });
  await page.goto('/');
  await page.locator('fieldset').filter({ has: page.locator('select option[value="industry"]:checked') }).getByLabel('值').fill('F51');
  const createdPromise = page.waitForResponse(response => response.url().endsWith('/api/v1/enterprises') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '保存当前样本' }).click();
  const created = await createdPromise;
  const enterprise = await created.json() as { id: string; period: { startDate: string; endDate: string }; facts: Array<{ key: string; value: unknown }> };
  expect(enterprise.facts.find(fact => fact.key === 'industry')?.value).toBe('F51');
  expect(enterprise.facts.find(fact => fact.key === 'region')?.value).toBe('440300');
  const etag = created.headers()['etag'];
  expect(etag).toBeTruthy();
  await expect(page.getByText('已保存合成企业：合成企业 A')).toBeVisible();
  await expect(page.getByText('ETag：服务未返回')).toHaveCount(0);
  await page.getByRole('button', { name: '机会列表' }).click();
  const card = page.locator('article').filter({ hasText: '合成联调：行业排除' });
  await expect(card).toBeVisible();
  await card.getByRole('checkbox').check();
  await page.getByRole('button', { name: '分析所选政策' }).click();
  await expect(card.getByText('不满足条件')).toBeVisible();
  await card.getByRole('button', { name: '查看详情' }).click();
  await expect(page.getByText('此处仅为接口结构演示，不是真实政策。')).toBeVisible();
  await page.screenshot({ path: 'test-results/live-exclusion.png', fullPage: true });
  const changed = await page.request.patch(`http://127.0.0.1:8000/api/v1/enterprises/${enterprise.id}/facts/industry`, {
    headers: { 'If-Match': etag }, data: { value: 'C39', unit: 'code', period: enterprise.period, source: 'user_input' },
  });
  expect(changed.status()).toBe(200);
  await page.goBack();
  await expect(card.getByText('依据已失效，待复核')).toBeVisible();
  await page.goForward();
  await expect(page.getByText('历史事实不可用')).toBeVisible();
  await expect(page.getByText('不满足条件').first()).toBeVisible();
  await page.getByRole('button', { name: '企业画像' }).click();
  await page.getByRole('button', { name: '复制为新样本' }).click();
  await page.locator('fieldset').filter({ has: page.locator('select option[value="industry"]:checked') }).getByLabel('值').fill('C39');
  await page.getByRole('button', { name: '添加事实' }).click();
  const market = page.locator('fieldset').last();
  await market.getByLabel('字段').selectOption('specificMarketSince');
  await market.getByRole('checkbox', { name: '未知' }).uncheck();
  await market.getByLabel('值').fill('2020-02-29');
  await page.getByRole('button', { name: '添加事实' }).click();
  const legal = page.locator('fieldset').last();
  await legal.getByLabel('字段').selectOption('independentLegalEntity');
  await legal.getByRole('checkbox', { name: '未知' }).uncheck();
  await legal.getByLabel('值').selectOption('true');
  const secondPromise = page.waitForResponse(response => response.url().endsWith('/api/v1/enterprises') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '保存当前样本' }).click();
  const second = await (await secondPromise).json() as { facts: Array<{ key: string; value: unknown }> };
  expect(second.facts.find(fact => fact.key === 'industry')?.value).toBe('C39');
  expect(second.facts.find(fact => fact.key === 'region')?.value).toBe('440300');
  expect(second.facts.find(fact => fact.key === 'specificMarketSince')?.value).toBe('2020-02-29');
  expect(second.facts.find(fact => fact.key === 'independentLegalEntity')?.value).toBe(true);
  await expect(page.getByText('已保存合成企业：合成企业 A')).toBeVisible();
  await page.getByRole('button', { name: '机会列表' }).click();
  const missing = page.locator('article').filter({ hasText: '合成联调：缺少所得额' });
  await expect(missing).toBeVisible();
  await missing.getByRole('checkbox').check();
  await page.getByRole('button', { name: '分析所选政策' }).click();
  await expect(missing.getByText('还缺资料')).toBeVisible();
  await missing.getByRole('button', { name: '查看详情' }).click();
  await expect(page.getByText('此处仅为接口结构演示，不是真实政策。')).toBeVisible();
  await page.screenshot({ path: 'test-results/live-missing.png', fullPage: true });
  await page.getByRole('button', { name: '机会列表' }).click();
  await expect(page.getByRole('heading', { name: '优先补充问题' })).toBeVisible();
  await page.getByRole('button', { name: '跳过（未知或不确定）' }).click();
  await expect(page.getByText(/当前没有需要补充的问题/)).toBeVisible();
  await page.getByRole('button', { name: '分析所选政策' }).click();
  await page.getByLabel('回答（CNY）').fill('10000');
  await page.getByRole('button', { name: '保存并重新分析' }).click();
  await expect(page.getByLabel('本次会话的分析历史')).toBeVisible();
  await page.getByRole('button', { name: '清单与报告' }).click();
  await expect(page.getByRole('heading', { name: '准备清单与报告' })).toBeVisible();
  const report = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载 Markdown 报告' }).click();
  expect((await report).suggestedFilename()).toMatch(/^assessment-.*\.md$/);
  await page.getByRole('button', { name: '机会列表' }).click();
  await page.getByRole('button', { name: '清空选择' }).click();
  const manual = page.locator('article').filter({ hasText: '合成联调：人工核查' });
  await manual.getByRole('checkbox').check();
  await page.getByRole('button', { name: '分析所选政策' }).click();
  await expect(manual.getByText('还缺资料')).toBeVisible();
  await manual.getByRole('button', { name: '查看详情' }).click();
  await expect(page.getByText(/请人工核查合成条件/).first()).toBeVisible();
});

test('隔离后端：税收与资金清单及多问题跳过', async ({ page }) => {
  test.skip(process.env.HUICE_LIVE !== '1', '仅在明确启动隔离联调服务时运行');
  await page.route('**/api/v1/**', route => new URL(route.request().url()).origin === 'http://127.0.0.1:8000' ? route.continue() : route.abort('blockedbyclient'));
  await page.goto('/'); await page.getByRole('button', { name: '保存当前样本' }).click();
  await page.getByRole('button', { name: '机会列表' }).click();
  const tax = page.locator('article').filter({ hasText: '合成联调：缺少所得额' });
  const grant = page.locator('article').filter({ hasText: '合成联调：资金多问题' });
  await tax.getByRole('checkbox').check(); await grant.getByRole('checkbox').check();
  await page.getByRole('button', { name: '分析所选政策' }).click();
  const question = page.getByRole('region', { name: '优先补充问题' });
  const first = await question.locator('p').first().textContent();
  await page.getByRole('button', { name: '跳过（未知或不确定）' }).click();
  await expect(question.locator('p').first()).not.toHaveText(first ?? '');
  await page.getByRole('button', { name: '清单与报告' }).click();
  for (const width of [375, 768, 1440]) {
    await page.setViewportSize({ width, height: 850 });
    await expect(page.getByRole('heading', { name: '税收优惠 · 自行判断' })).toBeVisible();
    await expect(page.getByRole('heading', { name: '资金项目 · 申请材料' })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    if (width === 375) await page.screenshot({ path: 'test-results/live-report-375.png', fullPage: true });
  }
});
